import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../app.js', import.meta.url),'utf8');
const start = source.indexOf('  const MODIFIERS =');
const end = source.indexOf('  function assignCameraBinding(',start);
const context = {}; vm.createContext(context);
vm.runInContext(source.slice(start,end)+';this.capture=keyCapture;',context);
const capture = e => context.capture(e,{});
assert.equal(capture({code:'KeyA',ctrlKey:true}).input.definition,'VK_LCONTROL+A');
assert.equal(capture({keyCode:49,ctrlKey:true,altKey:true}).input.definition,'VK_LCONTROL+VK_LMENU+1');
assert.equal(capture({key:'b'}).input.definition,'B');
assert.equal(capture({keyCode:97,location:3}).input.definition,'VK_NUMPAD1');
assert.equal(capture({keyCode:112}).input.definition,'VK_F1');
assert.equal(capture({keyCode:37}).input.definition,'VK_LEFT');
const held={}; assert.equal(context.capture({keyCode:17,location:2},held).pending,true);
assert.equal(context.capture({keyCode:65,ctrlKey:true},held).input.definition,'VK_RCONTROL+A');
assert.ok(capture({code:'Unidentified',keyCode:0}).error);
console.log('9 key capture regressions passed');
